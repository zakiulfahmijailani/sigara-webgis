import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
const base=process.env.SIGARA_TEST_URL||'http://127.0.0.1:3118';
const json=async(path,status=200)=>{const r=await fetch(base+path);assert.equal(r.status,status,path);return r.json();};
const full=await json('/api/showcase');
assert.equal(full.source,'neon');
assert.equal(full.data.episodes.length,3683);
assert.equal(full.data.summary.totals.visits,10776);
const localEpisodes=JSON.parse(await readFile('src/data/ntt-episodes.json','utf8'));
assert.deepEqual(full.data.episodes,localEpisodes);
const compact=await json('/api/showcase?compact=1');
assert.equal(compact.source,'neon');
assert.equal(compact.encoding,'episode-columns-v1');
assert.equal(compact.data.episodes.length,3683);
const selected='290411124Y000018';
const detail=await json('/api/showcase?episodeId='+selected);
assert.equal(detail.data.episodes.length,1);
assert.deepEqual(detail.data.episodes[0],localEpisodes.find(ep=>ep.id===selected));
const visits=await json('/api/showcase/visits?episodeId='+selected);
assert.equal(visits.source,'neon');
assert.equal(visits.count,detail.data.episodes[0].visitCount);
const localVisits=JSON.parse(await readFile('src/data/ntt-visits.json','utf8'));
assert.deepEqual(visits.visits,localVisits[selected]);
await json('/api/showcase/visits',400);
await json('/api/showcase?episodeId=',400);
await json('/api/showcase?episodeId=no-such-episode',404);
await json('/api/showcase?episodeId='+encodeURIComponent("' OR 1=1 --"),404);
const permissions='Read-only application API served actual Neon data; raw master never returned.';
const bytes=x=>Buffer.byteLength(JSON.stringify(x));
const gzip=x=>gzipSync(JSON.stringify(x)).length;
const report={checkedAt:new Date().toISOString(),base,source:full.source,episodes:3683,visits:10776,defaultBytes:bytes(full),compactBytes:bytes(compact),defaultGzipBytes:gzip(full),compactGzipBytes:gzip(compact),singleEpisodeBytes:bytes(detail),singleEpisodeVisits:visits.count,allEpisodeValuesEqual:true,selectedVisitValuesEqual:true,unknownEpisodeStatus:404,injectionLikeIdStatus:404,permissions};
if(process.env.SIGARA_REPORT)await writeFile(process.env.SIGARA_REPORT,JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
